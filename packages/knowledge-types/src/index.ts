export const EvalQuestionActionSchema = z.enum(EVAL_QUESTION_ACTIONS);
export type EvalQuestionAction = z.infer<typeof EvalQuestionActionSchema>;

/** `POST /eval/questions/:id` (owner): one of the owner's controls. */
export const EvalQuestionActionRequestSchema = z.strictObject({
  action: EvalQuestionActionSchema,
});
export type EvalQuestionActionRequest = z.infer<typeof EvalQuestionActionRequestSchema>;

export const EvalQuestionParamsSchema = z.object({ id: z.uuid() });

export const EvalQuestionResponseSchema = z.object({
  question: EvalQuestionDtoSchema,
  /** The question retired to make room, when a promotion needed one. */
  evicted: EvalQuestionDtoSchema.nullable(),
});
export type EvalQuestionResponse = z.infer<typeof EvalQuestionResponseSchema>;

/** `POST /eval/runs` (owner): a run was queued (or one is already waiting). 202. */
export const EvalRunAcceptedResponseSchema = z.object({ running: z.literal(true) });
export type EvalRunAcceptedResponse = z.infer<typeof EvalRunAcceptedResponseSchema>;
